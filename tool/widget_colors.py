#!/usr/bin/env python3
"""Writes the colours of the native widgets from Horizont's tokens.

The home screen widgets (Android RemoteViews, iOS WidgetKit) cannot read the
Flutter theme, so their colours are generated here from
tokens/horizont.json of the Horizont checkout given as the first argument
(default ../horizont). Run it after bumping Horizont.
"""
import json
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
tokens = json.loads((pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else root.parent / 'horizont') / 'tokens/horizont.json').read_text())
c = tokens['color']
p = c['product']['landbote']

def android(mode):
    n = c['neutral'][mode]
    a = p[mode]
    names = {'hz_bg': n['bg'], 'hz_line': n['line'], 'hz_text': n['text'], 'hz_text_muted': n['text-muted'], 'hz_accent_text': a['accent-text']}
    body = '\n'.join(f'    <color name="{k}">{v}</color>' for k, v in names.items())
    return f'<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tool/widget_colors.py from Horizont {tokens["version"]}. Do not edit. -->\n<resources>\n{body}\n</resources>\n'

res = root / 'android/app/src/main/res'
(res / 'values/widget_colors.xml').write_text(android('light'))
(res / 'values-night/widget_colors.xml').write_text(android('dark'))

def swift_color(hexstr):
    h = hexstr.lstrip('#')
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    return f'Color(red: {r:.4f}, green: {g:.4f}, blue: {b:.4f})'

lines = [f'// Generated by tool/widget_colors.py from Horizont {tokens["version"]}. Do not edit.', 'import SwiftUI', '', 'enum Hz {']
for key, name in [('bg', 'bg'), ('line', 'line'), ('text', 'text'), ('text-muted', 'textMuted')]:
    lines.append(f'  static func {name}(_ dark: Bool) -> Color {{ dark ? {swift_color(c["neutral"]["dark"][key])} : {swift_color(c["neutral"]["light"][key])} }}')
lines.append(f'  static func accentText(_ dark: Bool) -> Color {{ dark ? {swift_color(p["dark"]["accent-text"])} : {swift_color(p["light"]["accent-text"])} }}')
lines.append('}')
for target in ['ios/LandboteWidget', 'ios/LandboteWatch']:
    d = root / target
    d.mkdir(parents=True, exist_ok=True)
    (d / 'HzColors.swift').write_text('\n'.join(lines) + '\n')
print('ok', tokens['version'])
